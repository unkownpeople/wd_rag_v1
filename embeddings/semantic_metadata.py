"""为年报切块补充可过滤、可审计的报表语义元数据。

这里不调用 LLM，也不改变原始正文或表格矩阵。字段只从当前切块已经
存在的表头、行标签、章节路径和来源元数据中确定性推断；无法确定时
使用 ``unknown`` 或空值，避免把相似表格静默合并。
"""

