_DATE_RE = re.compile(
    r"\b(January|February|March|April|May|June|July|August|September|October|November|December)\s+"
    r"(\d{1,2}),\s*(\d{4})\b",
    re.IGNORECASE,
)
_YEAR_RE = re.compile(r"\b(?:FY\s*)?(19|20)\d{2}\b", re.IGNORECASE)
_UNIT_RE = re.compile(
    r"(?:in|₹|rs\.?|rupees?|\$|usd|eur|€|jpy|¥)\s*"
    r"(?:us\s*)?(million|millions|billion|billions|thousand|thousands|crore|crores|"
    r"lakh|lakhs|百万|亿元|千元)\b",
    re.IGNORECASE,
)


